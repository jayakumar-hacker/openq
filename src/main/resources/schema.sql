-- =====================================================================
-- OpenQ schema (PostgreSQL). Idempotent: safe to run on every start.
-- Hibernate runs with ddl-auto=validate, so this file is the single source of truth.
-- All *_time / *_at columns are clinic-local wall-clock time (TIMESTAMP WITHOUT TIME ZONE).
-- =====================================================================

CREATE TABLE IF NOT EXISTS doctor (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(120) NOT NULL,
    specialization VARCHAR(80)  NOT NULL,
    qualification  VARCHAR(120),
    clinic_name    VARCHAR(120) NOT NULL,
    email          VARCHAR(160) NOT NULL,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_doctor_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS slot (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id  BIGINT      NOT NULL REFERENCES doctor (id),
    start_time TIMESTAMP   NOT NULL,
    end_time   TIMESTAMP   NOT NULL,
    status     VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    version    BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_slot_times  CHECK (end_time > start_time),
    CONSTRAINT ck_slot_status CHECK (status IN ('AVAILABLE', 'BOOKED')),
    -- A doctor cannot have two slots starting at the same moment. Also makes seeding idempotent.
    CONSTRAINT uq_slot_doctor_start UNIQUE (doctor_id, start_time)
);

CREATE TABLE IF NOT EXISTS appointment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id       BIGINT       NOT NULL REFERENCES slot (id),
    patient_name  VARCHAR(100) NOT NULL,
    patient_email VARCHAR(160) NOT NULL,
    patient_phone VARCHAR(20),
    status        VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    cancelled_at  TIMESTAMP,
    CONSTRAINT ck_appointment_status CHECK (status IN ('BOOKED', 'CANCELLED')),
    -- cancelled_at is set if and only if the appointment is CANCELLED.
    CONSTRAINT ck_appointment_cancelled_at CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL))
);

-- ---------------------------------------------------------------------
-- DOUBLE-BOOKING GUARD (database-level, cannot be bypassed by application bugs):
-- at most ONE appointment per slot may be in status BOOKED.
-- CANCELLED rows are not covered by the index, so a cancelled slot can be booked again,
-- and any number of historic CANCELLED rows may exist for the same slot.
-- JPA has no annotation for partial indexes, which is why it lives here.
-- ---------------------------------------------------------------------
CREATE UNIQUE INDEX IF NOT EXISTS ux_appointment_active_slot
    ON appointment (slot_id)
    WHERE status = 'BOOKED';

-- Query-supporting indexes
-- (the UNIQUE constraint uq_slot_doctor_start already indexes doctor_id + start_time for schedule lookups)
CREATE INDEX IF NOT EXISTS ix_slot_open_by_doctor ON slot (doctor_id, start_time) WHERE status = 'AVAILABLE';
CREATE INDEX IF NOT EXISTS ix_slot_start_time     ON slot (start_time);
CREATE INDEX IF NOT EXISTS ix_appointment_status  ON appointment (status);
CREATE INDEX IF NOT EXISTS ix_appointment_slot    ON appointment (slot_id);
